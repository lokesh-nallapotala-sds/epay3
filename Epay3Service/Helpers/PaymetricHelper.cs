    public static int? GetCountryCode(string? countryCode) {
        if (string.IsNullOrEmpty(countryCode)) {
            return null;
        }

        if (CountryCodes.ContainsKey(countryCode)) {
            return CountryCodes[countryCode];
        }

        return null;
    }

    public static int? GetCurrencyCode(string? currency, string? country = null)
    {
        if (string.IsNullOrEmpty(currency)) {
            if (country != null && CountryCodeCurrencyCodeMap.ContainsKey(country))
            {
                return CountryCodeCurrencyCodeMap[country];
            }
            return null;
        }

        if (CurrencyCodes.ContainsKey(currency))
        {
            return CurrencyCodes[currency];
        }

        return null;
    }

    public static int GetCurrencyDecimal(string? currency) {
        if (string.IsNullOrEmpty(currency)) {
            return 2;
        }

        switch (currency) {
            case "JPY": return 4;
            default: return 2;
        }
    }
